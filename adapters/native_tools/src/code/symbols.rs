/// What tells that a file is as it was when it was indexed.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Stamp {
    /// Modified time in nanoseconds since the epoch (0 when the system does not say).
    pub modified_ns: u128,
    pub len: u64,
}

impl Stamp {
    pub fn of(meta: &std::fs::Metadata) -> Stamp {
        let modified_ns = meta.modified().ok().and_then(|t| t.duration_since(std::time::UNIX_EPOCH).ok()).map(|d| d.as_nanos()).unwrap_or(0);
        Stamp { modified_ns, len: meta.len() }
    }
}

/// What the index keeps of one file.
#[derive(Debug)]
pub struct Parsed {
    pub language: &'static str,
    pub symbols: Vec<Symbol>,
    /// What the file says it imports (card OA12-03: `code.deps` and `code.map` read these, so that one read of a file serves the symbols and the imports), empty for a language that is not read.
    pub imports: Vec<RawImport>,
    pub skipped: Option<Skipped>,
    bytes: usize,
}

struct Cached {
    stamp: Stamp,
    parsed: Arc<Parsed>,
    /// The generation of the last walk that met the file (the oldest go first when the index is over its cap).
    seen: u64,
}

#[derive(Default)]
struct Inner {
    files: HashMap<PathBuf, Cached>,
    bytes: usize,
    generation: u64,
}

/// The symbols of the files a walk has met, kept until a file changes.
pub struct SymbolIndex {
    inner: Mutex<Inner>,
    parses: AtomicUsize,
    cap: usize,
}

impl Default for SymbolIndex {
    fn default() -> Self {
        Self::new()
    }
}

/// Why the text of a file could not be had.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Unreadable {
    /// Not text, or not UTF-8 or UTF-16 free text: nothing to index.
    NotText,
    /// Could not be opened or read.
    Failed,
}

impl SymbolIndex {
    pub fn new() -> Self {
        Self::with_cap(INDEX_MEMORY_CAP)
    }

    /// An index that holds at most `cap` bytes of symbols.
    pub fn with_cap(cap: usize) -> Self {
        SymbolIndex { inner: Mutex::new(Inner::default()), parses: AtomicUsize::new(0), cap }
    }

    /// How many files have been parsed since the index was made (a test's way to see that an unchanged file is not parsed again).
    pub fn parses(&self) -> usize {
        self.parses.load(Ordering::SeqCst)
    }

    /// How many files the index holds, and the bytes it counts for them.
    pub fn size(&self) -> (usize, usize) {
        let i = self.inner.lock().unwrap_or_else(|e| e.into_inner());
        (i.files.len(), i.bytes)
    }

    /// A new generation for a walk: the number to give to [`SymbolIndex::get`] for each file it meets and to [`SymbolIndex::finish`].
    pub fn begin(&self) -> u64 {
        let mut i = self.inner.lock().unwrap_or_else(|e| e.into_inner());
        i.generation += 1;
        i.generation
    }

    /// The symbols of the file at `path` whose metadata says `stamp`: the kept ones when the file is as it was, else `read` is asked for the text and it is parsed. `file_name` decides the
    /// language. The text is read outside the lock, so that another call is not held up by a slow disk.
    pub fn get(&self, path: &Path, file_name: &str, stamp: Stamp, generation: u64, read: impl FnOnce() -> Result<String, Unreadable>) -> Result<Arc<Parsed>, Unreadable> {
        {
            let mut i = self.inner.lock().unwrap_or_else(|e| e.into_inner());
            if let Some(c) = i.files.get_mut(path) {
                if c.stamp == stamp {
                    c.seen = generation;
                    return Ok(c.parsed.clone());
                }
            }
        }
        let text = read()?;
        self.parses.fetch_add(1, Ordering::SeqCst);
        let parsed = Arc::new(parse_for_index(file_name, &text));
        let mut i = self.inner.lock().unwrap_or_else(|e| e.into_inner());
        if let Some(old) = i.files.remove(path) {
            i.bytes = i.bytes.saturating_sub(old.parsed.bytes);
        }
        // A file that alone is over the cap is not kept (it is parsed again next time).
        if parsed.bytes <= self.cap {
            while i.bytes + parsed.bytes > self.cap {
                let oldest = i.files.iter().min_by_key(|(_, c)| c.seen).map(|(p, _)| p.clone());
                let Some(oldest) = oldest else { break };
                if let Some(gone) = i.files.remove(&oldest) {
                    i.bytes = i.bytes.saturating_sub(gone.parsed.bytes);
                }
            }
            i.bytes += parsed.bytes;
            i.files.insert(path.to_path_buf(), Cached { stamp, parsed: parsed.clone(), seen: generation });
        }
        Ok(parsed)
    }

    /// The walk of the folder `root` ended having met every file it could: what the index holds under `root` that no walk of this generation met was deleted or hidden since, and goes.
    pub fn finish(&self, root: &Path, generation: u64) {
        let mut i = self.inner.lock().unwrap_or_else(|e| e.into_inner());
        let gone: Vec<PathBuf> = i.files.iter().filter(|(p, c)| c.seen < generation && p.starts_with(root)).map(|(p, _)| p.clone()).collect();
        for p in gone {
            if let Some(c) = i.files.remove(&p) {
                i.bytes = i.bytes.saturating_sub(c.parsed.bytes);
            }
        }
    }
}

fn parse_for_index(file_name: &str, text: &str) -> Parsed {
    let skipped = if is_generated(text) {
        Some(Skipped::Generated)
    } else if is_minified(text) {
        Some(Skipped::Minified)
    } else {
        None
    };
    if skipped.is_some() {
        return Parsed { language: "text", symbols: Vec::new(), imports: Vec::new(), skipped, bytes: 96 };
    }
    let o = symbols_of(file_name, text);
    let imports = graph::imports_of(file_name, text);
    let bytes = 96 + o.symbols.iter().map(|s| 120 + s.name.len() + s.parent.len() + s.signature.len()).sum::<usize>() + imports.iter().map(RawImport::weight).sum::<usize>();
    Parsed { language: o.language, symbols: o.symbols, imports, skipped: None, bytes }
}

