    #[test]
    fn the_best_answers_are_kept_in_order_whatever_the_order_they_came_in() {
        let q = Query::new("run", None).unwrap();
        let file = |rel: &str, names: &[&str]| (rel.to_string(), names.iter().map(|n| sym("fn", n, "", true)).collect::<Vec<_>>());
        let files = [file("b.rs", &["runner", "run"]), file("a.rs", &["run", "rerun", "unrelated"]), file("c.rs", &["run_all"])];
        let collect = |order: &[usize]| {
            let mut top = TopHits::new(3);
            for &i in order {
                top.offer_file(&q, &files[i].0, &files[i].1);
            }
            let lines = hit_lines(&top.hits);
            (lines, top.matched, top.files_with_matches)
        };
        let (a, matched, in_files) = collect(&[0, 1, 2]);
        let (b, _, _) = collect(&[2, 1, 0]);
        assert_eq!(a, b, "the order of the folder does not change the answer");
        assert_eq!((matched, in_files), (5, 3));
        assert_eq!(a[0], "a.rs:1 fn run");
        assert_eq!(a[1], "b.rs:1 fn run");
        assert_eq!(a.len(), 3);
    }

    #[test]
    fn collectors_that_saw_some_of_the_files_each_give_together_what_one_that_saw_all_gives() {
        let q = Query::new("handler", None).unwrap();
        let files: Vec<(String, Vec<Symbol>)> = (0..40).map(|i| (format!("pkg{:02}/m.rs", (i * 7) % 40), vec![sym("fn", &format!("handler_{i:02}"), "", i % 3 != 0), sym("fn", "unrelated", "", true)])).collect();
        let mut whole = TopHits::new(6);
        for (rel, symbols) in &files {
            whole.offer_file(&q, rel, symbols);
        }
        let (mut left, mut right) = (TopHits::new(6), TopHits::new(6));
        for (i, (rel, symbols)) in files.iter().enumerate() {
            let half = if i % 2 == 0 { &mut left } else { &mut right };
            half.offer_file(&q, rel, symbols);
        }
        left.merge(right);
        assert_eq!(hit_lines(&left.hits), hit_lines(&whole.hits));
        assert_eq!((left.matched, left.files_with_matches), (whole.matched, whole.files_with_matches));
        assert_eq!((whole.matched, whole.files_with_matches, whole.hits.len()), (40, 40, 6));
        // The public ones come first, and among them the shorter path.
        assert!(whole.hits.iter().all(|h| h.symbol.public), "{:?}", hit_lines(&whole.hits));
    }
