/// The lower-case letters and digits of `s`, and nothing else.
fn compact(s: &str) -> String {
    s.chars().filter(|c| c.is_alphanumeric()).flat_map(|c| c.to_lowercase()).collect()
}

/// The words of a name or a phrase, lower case: `parseConfig`, `parse_config`, `HTTPServer` and `parse config` are `parse config` and `http server`.
pub fn words_of(s: &str) -> Vec<String> {
    let mut words: Vec<String> = Vec::new();
    let mut cur = String::new();
    let chars: Vec<char> = s.chars().collect();
    for (i, &c) in chars.iter().enumerate() {
        if !c.is_alphanumeric() {
            if !cur.is_empty() {
                words.push(std::mem::take(&mut cur));
            }
            continue;
        }
        if c.is_uppercase() && !cur.is_empty() {
            let prev = chars[i - 1];
            let next_lower = chars.get(i + 1).is_some_and(|n| n.is_lowercase());
            // `parseConfig` (a lower or a digit, then a capital) and the end of an acronym (`HTTPServer`: the S).
            if prev.is_lowercase() || prev.is_ascii_digit() || (prev.is_uppercase() && next_lower) {
                words.push(std::mem::take(&mut cur));
            }
        }
        cur.extend(c.to_lowercase());
    }
    if !cur.is_empty() {
        words.push(cur);
    }
    words
}

/// The kinds a call may ask for, with what each means.
pub const KINDS: &[&str] = &["function", "method", "class", "struct", "enum", "trait", "interface", "type", "const", "module", "impl"];

/// The group of kinds that a word asks for: `function` is every function and method, `trait` and `interface` are one, `module` and `namespace` are one.
fn kind_group(word: &str) -> Option<&'static [&'static str]> {
    Some(match word.to_ascii_lowercase().as_str() {
        "function" | "func" | "fn" | "def" | "method" => &["fn", "function", "func", "method"][..],
        "class" => &["class"][..],
        "struct" => &["struct"][..],
        "enum" => &["enum"][..],
        "trait" | "interface" => &["trait", "interface"][..],
        "type" => &["type"][..],
        "const" | "constant" | "static" | "var" | "let" => &["const", "static"][..],
        "module" | "mod" | "namespace" => &["mod", "namespace"][..],
        "impl" => &["impl"][..],
        _ => return None,
    })
}

/// What a call asks: the words, and perhaps a kind.
#[derive(Debug, Clone)]
pub struct Query {
    pub text: String,
    compact: String,
    words: Vec<String>,
    kinds: Option<&'static [&'static str]>,
}

impl Query {
    /// `kind` is one of [`KINDS`] (or a spelling of one: `func`, `fn`, `def`, `interface`...); anything else is an error that lists them.
    pub fn new(text: &str, kind: Option<&str>) -> Result<Query, String> {
        let text = text.trim().to_string();
        let compact = compact(&text);
        if compact.is_empty() {
            return Err("the query has no letters or digits: give a name or some words of one".into());
        }
        let kinds = match kind.map(str::trim).filter(|k| !k.is_empty()) {
            None => None,
            Some(k) => Some(kind_group(k).ok_or_else(|| format!("kind '{k}' is not one of: {}", KINDS.join(", ")))?),
        };
        let words = words_of(&text);
        Ok(Query { text, compact, words, kinds })
    }

    fn kind_ok(&self, s: &Symbol) -> bool {
        self.kinds.map_or(true, |k| k.contains(&s.kind))
    }

    /// How well `s`, in a file whose path has the words `path_words`, answers the query; `None` when it does not at all. Higher is better.
    pub fn score(&self, s: &Symbol, path_words: &[String]) -> Option<u32> {
        if !self.kind_ok(s) {
            return None;
        }
        let name = compact(&s.name);
        if name.is_empty() {
            return None;
        }
        let name_words = words_of(&s.name);
        let parent_words = words_of(&s.parent);
        let has = |haystack: &[String], w: &str| haystack.iter().any(|h| h == w);
        let starts = |haystack: &[String], w: &str| haystack.iter().any(|h| h.starts_with(w));
        let in_name = self.words.iter().filter(|w| has(&name_words, w)).count();
        let in_name_or_start = self.words.iter().filter(|w| starts(&name_words, w)).count();
        let in_any = self.words.iter().filter(|w| starts(&name_words, w) || starts(&parent_words, w)).count();
        let all = self.words.len();
        let base = if name == self.compact {
            10_000
        } else if name.starts_with(&self.compact) {
            // The nearer the name is to the query in length, the better.
            8_000u32.saturating_sub((name.len() - self.compact.len()).min(500) as u32)
        } else if all > 0 && in_name == all {
            6_000
        } else if all > 0 && in_any == all && in_name_or_start >= 1 {
            5_500
        } else if all > 0 && in_name_or_start == all {
            5_000
        } else if name.contains(&self.compact) {
            4_000
        } else if all > 0 && in_any >= 1 && in_name_or_start >= 1 {
            1_000 + (2_000 * in_any / all) as u32
        } else {
            return None;
        };
        // A word of the path counts a little (`config.rs` for `parse config`), and so does a public name.
        let path_bonus = self.words.iter().filter(|w| has(path_words, w)).count().min(3) as u32 * 40;
        Some(base + path_bonus + u32::from(s.public) * 20)
    }
}

/// One answer, with what orders it.
#[derive(Debug, Clone)]
pub struct Hit {
    pub score: u32,
    pub rel: String,
    pub symbol: Symbol,
}

/// What orders the answers: the higher score first, then a public symbol, a less deep one, a shorter name, then the path and the line (so that the answer does not depend on the order the
/// folder was walked in, or on which thread met a file first).
struct HitKey<'a> {
    score: u32,
    public: bool,
    depth: usize,
    name_len: usize,
    rel: &'a str,
    start: usize,
}

fn order(a: &HitKey<'_>, b: &HitKey<'_>) -> std::cmp::Ordering {
    b.score
        .cmp(&a.score)
        .then_with(|| b.public.cmp(&a.public))
        .then_with(|| a.depth.cmp(&b.depth))
        .then_with(|| a.name_len.cmp(&b.name_len))
        .then_with(|| a.rel.cmp(b.rel))
        .then_with(|| a.start.cmp(&b.start))
}

impl Hit {
    fn key(&self) -> HitKey<'_> {
        HitKey { score: self.score, public: self.symbol.public, depth: self.symbol.depth, name_len: self.symbol.name.len(), rel: &self.rel, start: self.symbol.start }
    }
}

/// The best `limit` answers so far, and how many answered at all.
pub struct TopHits {
    limit: usize,
    pub hits: Vec<Hit>,
    pub matched: usize,
    pub files_with_matches: usize,
}

impl TopHits {
    pub fn new(limit: usize) -> TopHits {
        TopHits { limit: limit.max(1), hits: Vec::new(), matched: 0, files_with_matches: 0 }
    }

    /// Where an answer with this key goes among the best, or `None` when it is not one of the best `limit`.
    fn place(&self, key: &HitKey<'_>) -> Option<usize> {
        let at = self.hits.partition_point(|h| order(&h.key(), key) != std::cmp::Ordering::Greater);
        (at < self.limit).then_some(at)
    }

    fn put(&mut self, at: usize, hit: Hit) {
        self.hits.insert(at, hit);
        self.hits.truncate(self.limit);
    }

    /// Offers the symbols of one file (`rel` is how it is named in the answer). A symbol that is not one of the best is not copied.
    pub fn offer_file(&mut self, q: &Query, rel: &str, symbols: &[Symbol]) {
        let path_words = words_of(rel);
        let mut any = false;
        for s in symbols {
            let Some(score) = q.score(s, &path_words) else { continue };
            any = true;
            self.matched += 1;
            let key = HitKey { score, public: s.public, depth: s.depth, name_len: s.name.len(), rel, start: s.start };
            if let Some(at) = self.place(&key) {
                self.put(at, Hit { score, rel: rel.to_string(), symbol: s.clone() });
            }
        }
        if any {
            self.files_with_matches += 1;
        }
    }

    /// Takes the answers of another collector (made from other files, perhaps on another thread): the best of both are kept, in the order one collector that saw all of them would have.
    pub fn merge(&mut self, other: TopHits) {
        self.matched += other.matched;
        self.files_with_matches += other.files_with_matches;
        for hit in other.hits {
            let at = self.place(&hit.key());
            if let Some(at) = at {
                self.put(at, hit);
            }
        }
    }
}

/// The lines of `code.symbols`: `file:line kind name signature`, best first. (`fn` is in the signature, so the kind is only said when the signature does not begin with it.)
pub fn hit_lines(hits: &[Hit]) -> Vec<String> {
    hits.iter()
        .map(|h| {
            let parent = if h.symbol.parent.is_empty() || h.symbol.signature.contains(&h.symbol.parent) { String::new() } else { format!(" [in {}]", h.symbol.parent) };
            format!("{}:{} {}{parent}", h.rel, h.symbol.start, h.symbol.signature)
        })
        .collect()
}

