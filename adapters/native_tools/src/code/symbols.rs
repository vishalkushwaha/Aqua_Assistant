//! The symbols of source files and a search over them (card OA12-02; tasks CU-08 and TL-13 of the OpenCode audit).
//!
//! A model with a 6,144-token window cannot read a source file to find one function, and a grep for a name gives lines, not what a name is. This is what `code.outline` (what is in one
//! file) and `code.symbols` (where is X defined, in the whole folder) are made of. It is **not a parser**: the declarations come from the shape of the lines, as `fs::outline` has them
//! (the keyword that begins a declaration, the braces or the indentation that end it), because no grammar crate is a dependency of this build. A macro or a string that breaks the count of
//! braces gives a range that ends where the declaration begins, and the output says "from the shape of the lines" in its first line. Nothing here reads a file or runs anything: the caller
//! gives the text, and the guard, the walker and the limits are the file tools' own (see [`super::provider`]).
//!
//! * [`symbols_of`] makes the symbols of one file: each has its kind, name, lines, depth, the name of what it is inside, its first line (the signature) and whether it is public.
//! * [`SymbolIndex`] keeps them, per file, until the file changes (its modified time or its length): a call looks at every file's metadata and parses only what is new or changed.
//!   Files over 1 MiB, files that say they are generated, and minified ones are not indexed. The index is in memory, capped at 50 MiB, and is never written to disk. It keeps what a file
//!   says it imports too (card OA12-03, see [`super::graph`]), made in the same pass, so that `code.deps` and `code.map` read a file once for both.
//! * [`Query`] and [`Hit`] rank: an exact name, then a name that begins with the query, then names whose words (snake_case and camelCase are split) are the query's, then a name that holds it,
//!   then names that share some of its words (with the name of what they are inside and the words of the path counting a little). Ties go to a public symbol, a less deep one, a shorter
//!   name, then the path and line, so that the answer does not depend on the order the folder was walked in.

use super::graph::{self, RawImport};
use crate::fs::outline::{self, Item};
use std::collections::HashMap;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::{Arc, Mutex};

/// The largest file that is indexed or outlined.
pub const MAX_FILE_BYTES: u64 = 1 << 20;
/// The most lines of a file that are looked at.
pub const MAX_LINES: usize = 20_000;
/// The most characters of a signature (the first line of a declaration).
pub const MAX_SIGNATURE_CHARS: usize = 100;
/// The most memory the index may use, in bytes (counted from the text of its symbols).
pub const INDEX_MEMORY_CAP: usize = 50 << 20;
/// The files `code.symbols` looks in: the languages whose declarations `fs::outline` knows by their keywords.
pub const SOURCE_GLOB: &str = "*.{rs,py,pyi,ts,tsx,mts,cts,js,jsx,mjs,cjs,go,java,kt,cs,c,h,cpp,cc,hpp,php,swift,scala}";
/// A file with lines longer than this on average (and over 20,000 bytes) is minified, and has no symbols worth showing.
const MINIFIED_LINE_AVERAGE: usize = 500;
const MINIFIED_MIN_BYTES: usize = 20_000;
/// The words of the first lines of a file that say it was made by a program.
const GENERATED_MARKERS: &[&str] = &["@generated", "DO NOT EDIT", "Code generated", "<auto-generated", "automatically generated", "autogenerated", "auto-generated"];

/// One declaration of a file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Symbol {
    /// `fn`, `struct`, `class`, `method`, `function`, `h2`, ... (the kinds of `fs::outline`).
    pub kind: &'static str,
    pub name: String,
    /// The first and the last line (1-based, inclusive).
    pub start: usize,
    pub end: usize,
    /// How many declarations it is inside.
    pub depth: usize,
    /// What it is inside (`Thing` for a method of `impl Thing`, `impl fmt::Display for Thing` and a Go method of `*Thing`), or empty at the top of the file.
    pub parent: String,
    /// The first line of the declaration without its opening brace, cleaned of control characters and cut at [`MAX_SIGNATURE_CHARS`].
    pub signature: String,
    /// Whether the language calls it public (`pub`, `export`, a Python name with no leading underscore, a Go name with a capital): for the order of equal matches only.
    pub public: bool,
}

/// The symbols of one file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FileOutline {
    pub language: &'static str,
    pub total_lines: usize,
    pub symbols: Vec<Symbol>,
    /// The file has more than [`MAX_LINES`] lines: only those were looked at.
    pub lines_cut: bool,
}

/// Why a file has no symbols in the index although it was met.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Skipped {
    Generated,
    Minified,
}

/// Does the head of the file say that a program made it?
pub fn is_generated(text: &str) -> bool {
    text.lines().take(5).any(|l| {
        let l = l.trim_start();
        let comment = l.starts_with("//") || l.starts_with('#') || l.starts_with("/*") || l.starts_with('*') || l.starts_with("<!--") || l.starts_with("--");
        comment && GENERATED_MARKERS.iter().any(|m| l.contains(m))
    })
}

/// Is it a file of very long lines (a bundle, a minified script)?
pub fn is_minified(text: &str) -> bool {
    text.len() > MINIFIED_MIN_BYTES && text.len() / (text.bytes().filter(|b| *b == b'\n').count() + 1) > MINIFIED_LINE_AVERAGE
}

/// The first `MAX_LINES` lines of `text`, and whether there were more.
fn cap_lines(text: &str) -> (&str, bool) {
    let mut seen = 0usize;
    for (i, b) in text.bytes().enumerate() {
        if b == b'\n' {
            seen += 1;
            if seen == MAX_LINES {
                let rest = &text[i + 1..];
                return (&text[..i + 1], !rest.is_empty());
            }
        }
    }
    (text, false)
}

/// The signature of a declaration: its first line, trimmed, without the brace or colon that opens its body.
fn signature_of(line: &str) -> String {
    let t = line.trim();
    let t = t.trim_end_matches('{').trim_end();
    let t = t.strip_suffix(':').unwrap_or(t).trim_end();
    let cleaned: String = t.chars().map(|c| if c.is_control() { ' ' } else { c }).collect();
    let cleaned = cleaned.split_whitespace().collect::<Vec<_>>().join(" ");
    if cleaned.chars().count() > MAX_SIGNATURE_CHARS {
        format!("{}…", cleaned.chars().take(MAX_SIGNATURE_CHARS).collect::<String>().trim_end())
    } else {
        cleaned
    }
}

/// `impl fmt::Display for Thing` -> `Thing`; `impl Thing` -> `Thing`; `impl<T> From<T> for Foo<T>` is `Foo`.
fn parent_label(kind: &str, name: &str) -> String {
    if kind != "impl" {
        return name.to_string();
    }
    let target = name.rsplit_once(" for ").map(|(_, t)| t).unwrap_or(name);
    let target = target.split('<').next().unwrap_or(target).trim();
    target.rsplit("::").next().unwrap_or(target).trim().to_string()
}

/// The type a Go method is declared on: `func (s *Server) Run() error` -> `Server`.
fn go_receiver(line: &str) -> Option<String> {
    let rest = line.trim_start().strip_prefix("func")?.trim_start().strip_prefix('(')?;
    let inside = rest.split(')').next()?;
    let ty = inside.split_whitespace().last()?.trim_start_matches('*');
    let ty = ty.split('[').next().unwrap_or(ty);
    (!ty.is_empty()).then(|| ty.to_string())
}

fn is_public(language: &str, line: &str, name: &str, kind: &str) -> bool {
    let line = line.trim_start();
    match language {
        "rust" => line.starts_with("pub"),
        "typescript" | "javascript" => line.starts_with("export") || (kind == "method" && !line.starts_with("private") && !line.starts_with("protected") && !line.starts_with('#')),
        "python" => !name.starts_with('_'),
        "go" => name.chars().next().is_some_and(|c| c.is_uppercase()),
        _ => !line.contains("private") && !line.contains("internal"),
    }
}

/// The symbols of `text`, a file called `file_name`. Not a parse: see the module's description.
pub fn symbols_of(file_name: &str, text: &str) -> FileOutline {
    let (text, lines_cut) = cap_lines(text);
    let found = outline::outline(file_name, text);
    let lines: Vec<&str> = text.lines().map(|l| l.strip_prefix('\u{feff}').unwrap_or(l)).collect();
    let mut stack: Vec<(usize, String)> = Vec::new();
    let mut symbols = Vec::with_capacity(found.items.len());
    for Item { kind, name, start, end, depth } in found.items {
        while stack.last().is_some_and(|(e, _)| *e < start) {
            stack.pop();
        }
        let line = lines.get(start.saturating_sub(1)).copied().unwrap_or("");
        let mut parent = stack.last().map(|(_, n)| n.clone()).unwrap_or_default();
        if found.language == "go" && depth == 0 {
            if let Some(receiver) = go_receiver(line) {
                parent = receiver;
            }
        }
        stack.push((end, parent_label(kind, &name)));
        let public = is_public(found.language, line, &name, kind);
        symbols.push(Symbol { kind, name, start, end, depth, parent, signature: signature_of(line), public });
    }
    FileOutline { language: found.language, total_lines: found.total_lines, symbols, lines_cut }
}

// ---- the text of an outline -------------------------------------------------------------------------------------------------------

/// How many symbols to show of `symbols`: the ones nearest the top of the file's structure first (every top-level one, then the next depth...), returned in the order of the file.
fn choose(symbols: &[Symbol], max: usize) -> Vec<&Symbol> {
    if symbols.len() <= max {
        return symbols.iter().collect();
    }
    let mut taken = vec![false; symbols.len()];
    let mut left = max;
    let deepest = symbols.iter().map(|s| s.depth).max().unwrap_or(0);
    for d in 0..=deepest {
        for (i, s) in symbols.iter().enumerate() {
            if left == 0 {
                break;
            }
            if s.depth == d {
                taken[i] = true;
                left -= 1;
            }
        }
    }
    symbols.iter().zip(taken).filter(|(_, t)| *t).map(|(s, _)| s).collect()
}

/// The text of `code.outline`: a first line that says what it is, then one line for each symbol (`L120-188 fn parse_config(path: &Path) -> Config`), indented by how deep it is, at most
/// `max_symbols` of them and no more than `budget_chars` characters; what is left out is counted.
pub fn render_outline(shown_path: &str, o: &FileOutline, max_symbols: usize, budget_chars: usize) -> String {
    let total = o.symbols.len();
    let picked = choose(&o.symbols, max_symbols.max(1));
    let lines: Vec<String> = picked
        .iter()
        .map(|s| {
            let span = if s.end > s.start { format!("L{}-{}", s.start, s.end) } else { format!("L{}", s.start) };
            format!("{span} {}{}", "  ".repeat(s.depth), s.signature)
        })
        .collect();
    let cut = if o.lines_cut { format!("; only the first {MAX_LINES} lines were read") } else { String::new() };
    if lines.is_empty() {
        return format!("{shown_path}: {} lines, no symbols found ({} outline from the shape of the lines{cut}); read it with fs.read", o.total_lines, o.language);
    }
    let room = budget_chars.saturating_sub(shown_path.chars().count() + 280);
    let fits = crate::fs::page::fit_lines(&lines, room);
    let head = format!("{shown_path}: {} lines, {total} symbols (showing {fits}); {} outline from the shape of the lines, not a parse{cut}", o.total_lines, o.language);
    let mut text = format!("{head}\n{}", lines[..fits].join("\n"));
    if fits < total {
        text.push_str(&format!("\n… {} more symbols not shown; read a range with fs.read offset_line, or ask for fewer with a narrower file", total - fits));
    }
    text
}

